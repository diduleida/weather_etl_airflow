CREATE TABLE IF NOT EXISTS weather_raw(
    visibility BIGINT,
    datetime TIMESTAMPTZ NOT NULL,
    timezone BIGINT,
    id BIGINT NOT NULL,
    name VARCHAR NOT NULL,
    cod INT,
    longitude FLOAT,
    latitude FLOAT,
    temperature FLOAT,
    feels_like FLOAT,
    temp_min FLOAT,
    temp_max FLOAT,
    pressure INT,
    humidity INT,
    sea_level INT,
    ground_level INT,
    wind_speed FLOAT,
    wind_deg INT,
    wind_gust FLOAT,
    cloudiness INT,
    country VARCHAR NOT NULL,
    sunrise TIMESTAMPTZ,
    sunset TIMESTAMPTZ,
    rain_1h FLOAT,
    weather_id INT,
    weather_main VARCHAR,
    weather_description VARCHAR,
    weather_icon VARCHAR,

    PRIMARY KEY (datetime, id)
)